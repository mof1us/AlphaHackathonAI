CREATE TABLE news (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    text TEXT NOT NULL,
    date TIMESTAMPTZ NOT NULL,
    origin TEXT NOT NULL,
    is_indexed BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE business (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT,
    is_indexed BOOLEAN NOT NULL DEFAULT FALSE
);
